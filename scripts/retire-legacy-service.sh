#!/bin/bash
#
# Retire what Townmouse 0.2.x left under TerminalOne's name. Those versions
# installed the service as `com.floyd.terminalone` on port 11001 and wrote their
# launcher as `t1`, so Townmouse displaced TerminalOne on any Mac that had both.
# Only artifacts that are provably Townmouse's are removed: a plist under the
# TerminalOne label whose program is a Townmouse server, and a `t1` launcher that
# names itself a Townmouse launcher. TerminalOne's own service and launcher are
# never touched.
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
APP_DIR="${TERMINALONE_APP_DIR:-$(cd "$SCRIPT_DIR/.." && pwd -P)}"
LEGACY_LABEL="com.floyd.terminalone"
DOMAIN="gui/$(id -u)"
PLIST_DIR="${TERMINALONE_PLIST_DIR:-$HOME/Library/LaunchAgents}"
LEGACY_PLIST="$PLIST_DIR/$LEGACY_LABEL.plist"
LEGACY_STUB_MARKER='# Townmouse launcher — generated by install-service.sh'

legacy_server_path() {
  sed -n 's/.*<string>\([^<]*\/src\/server\.js\)<\/string>.*/\1/p' "$LEGACY_PLIST" | head -n 1
}

# Says whether the launch agent under TerminalOne's label runs Townmouse.
#   0  it runs Townmouse: this installation's server, or a server that belongs
#      to a package named townmouse
#   1  it runs another product: a package beside the server is named something else
#   2  it cannot be told: no package beside the server, and the folder is not
#      literally named townmouse
# The folder name is the last resort, because an engine vendored at
# .../townmouse/terminalone/src/server.js belongs to TerminalOne.
is_townmouse_plist() {
  local server package
  grep -Fq "<string>$APP_DIR/src/server.js</string>" "$LEGACY_PLIST" && return 0
  server="$(legacy_server_path)"
  [ -n "$server" ] || return 2
  package="$(dirname "$server")/../package.json"
  if [ -f "$package" ]; then
    if grep -Eq '"name"[[:space:]]*:[[:space:]]*"townmouse"' "$package"; then return 0; fi
    return 1
  fi
  if printf '%s\n' "$server" | grep -Eiq '(^|/)townmouse/src/server\.js$'; then return 0; fi
  return 2
}

if [ -f "$LEGACY_PLIST" ]; then
  verdict=0
  is_townmouse_plist || verdict=$?
  case "$verdict" in
    0)
      launchctl bootout "$DOMAIN/$LEGACY_LABEL" 2>/dev/null || true
      rm -f "$LEGACY_PLIST"
      echo "  legacy: removed the Townmouse service that 0.2.x installed as $LEGACY_LABEL."
      echo "  legacy: TerminalOne's own service, if you use it, comes back by running its scripts/install-service.sh."
      ;;
    2)
      echo "  legacy: a launch agent named $LEGACY_LABEL exists and could not be told from Townmouse's, so it was left alone."
      echo "  legacy: if it runs Townmouse 0.2.x, stop it by hand: launchctl bootout $DOMAIN/$LEGACY_LABEL"
      ;;
  esac
fi

if [ -n "${TERMINALONE_BIN_DIR:-}" ]; then
  LAUNCHER_DIRS=("$TERMINALONE_BIN_DIR")
else
  LAUNCHER_DIRS=(/usr/local/bin "$HOME/.local/bin" "$HOME/bin")
fi
for dir in "${LAUNCHER_DIRS[@]}"; do
  [ -n "$dir" ] || continue
  stub="$dir/t1"
  if [ -f "$stub" ] && [ ! -L "$stub" ] && grep -qF "$LEGACY_STUB_MARKER" "$stub" 2>/dev/null; then
    rm -f "$stub"
    echo "  legacy: removed $stub, the t1 launcher that 0.2.x wrote for Townmouse."
  fi
done
