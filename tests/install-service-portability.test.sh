#!/bin/bash
set -euo pipefail

# Exercises what the macOS service installer and uninstaller write: a launchd
# plist, a launcher on the internal disk, and a native app bundle (BSD stat and
# Mach-O output). launchctl, node and swiftc are faked, HOME is redirected, the
# caller's overrides are cleared, and every output lands under one temporary
# directory, so nothing real is started, registered or removed. Browser/server
# portability is covered on Linux by npm test.
if [ "$(uname -s)" != "Darwin" ]; then
  echo "SKIP: native app installer portability requires macOS (BSD stat and Mach-O)."
  exit 0
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TMP="$(cd "$(mktemp -d)" && pwd -P)"
trap 'rm -rf "$TMP"' EXIT

LABEL_TOWNMOUSE="com.floyd.townmouse"
LABEL_TERMINALONE="com.floyd.terminalone"
DOMAIN="gui/$(id -u)"
# The first line of a launcher stub this installer writes. 0.2.x wrote a stub
# with the same first line, but named it `t1`.
STUB_MARKER='# Townmouse launcher — generated by install-service.sh'

fail() {
  echo "FAIL: $*"
  exit 1
}

# The uninstaller removes bundles and launchers by path. Refuse to run unless the
# directory it is about to touch is inside this test's temporary directory.
outside_tmp() {
  case "$1" in
    "$TMP"/*) return 1 ;;
    *) return 0 ;;
  esac
}

SRC="$TMP/alt-checkout"
FAKEBIN="$TMP/fakebin"
mkdir -p "$SRC/scripts" "$SRC/src" "$SRC/public" "$SRC/native" "$FAKEBIN"
for script in install-service.sh uninstall-service.sh retire-legacy-service.sh townmouse.sh node-runtime.sh run-hooks; do
  cp "$ROOT/scripts/$script" "$SRC/scripts/$script"
done
cp "$ROOT/package.json" "$SRC/package.json"
cp "$ROOT/native/TownmouseApp.swift" "$SRC/native/TownmouseApp.swift"
cp "$ROOT/src/server.js" "$SRC/src/server.js"
cp "$ROOT/public/icon-512.png" "$SRC/public/icon-512.png"
chmod +x "$SRC/scripts/"*

cat > "$FAKEBIN/node" <<'EOF'
#!/bin/bash
case "${1:-}" in
  -p) echo 22 ;;
  -) : ;;
esac
exit 0
EOF

cat > "$FAKEBIN/launchctl" <<'EOF'
#!/bin/bash
echo "$*" >> "$LAUNCHCTL_LOG"
if [ "${1:-}" = "print" ]; then
  exit 1
fi
exit 0
EOF

cat > "$FAKEBIN/swiftc" <<'EOF'
#!/bin/bash
set -euo pipefail
echo "$*" >> "$SWIFTC_LOG"
out=""
while [ "$#" -gt 0 ]; do
  if [ "$1" = "-o" ]; then out="$2"; shift 2; else shift; fi
done
[ -n "$out" ]
cp /bin/echo "$out"
chmod +x "$out"
EOF

chmod +x "$FAKEBIN/node" "$FAKEBIN/launchctl" "$FAKEBIN/swiftc"

# Every run starts from a clean slate: a PORT or override exported in the
# caller's shell must not reach the scripts under test.
CLEAN=(env -u PORT -u TERMINALONE_APP_DIR -u TERMINALONE_NODE -u TERMINALONE_PLIST_DIR
  -u TERMINALONE_SYSTEM_LOG_DIR -u TERMINALONE_LOG_DIR -u TERMINALONE_URL
  -u TERMINALONE_HEALTH_URL -u TERMINALONE_TRUSTED_ORIGINS -u TERMINALONE_BIN_DIR
  -u TERMINALONE_APPLICATIONS_DIR -u TERMINALONE_SKIP_RUNTIME_CHECK -u TERMINALONE_SWIFTC
  -u TERMINALONE_SKIP_LSREGISTER)

# A stand-in for npm's own command for the package: a symlink named `townmouse`
# that points into a global npm prefix. The installer must not overwrite it and
# the uninstaller must not remove it.
NPM_TARGET="$TMP/npm-prefix/lib/node_modules/townmouse/bin/townmouse"
mkdir -p "$TMP/npm-prefix/lib/node_modules/townmouse/bin"
printf '#!/usr/bin/env node\n' > "$NPM_TARGET"

# write_plist <file> <server.js the agent runs>
write_plist() {
  cat > "$1" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$(basename "$1" .plist)</string>
  <key>ProgramArguments</key>
  <array>
    <string>/usr/local/bin/node</string>
    <string>$2</string>
  </array>
</dict>
</plist>
PLIST
}

# new_site <name>: a fresh user with its own HOME, Applications folder and bin.
new_site() {
  SITE="$TMP/$1"
  HOME_DIR="$SITE/home"
  APP_PARENT="$SITE/apps"
  BIN_DIR="$SITE/bin"
  AGENTS="$HOME_DIR/Library/LaunchAgents"
  mkdir -p "$APP_PARENT" "$BIN_DIR" "$AGENTS"
}

# run_tool <site> <script> <event log>: runs the script on the site and returns
# its exit status, with its output kept in <site>/<script>.out.
run_tool() {
  local site="$1" script="$2" log="$3"
  if outside_tmp "$site/apps" || outside_tmp "$site/bin" || outside_tmp "$site/home"; then
    fail "refusing to run $script outside $TMP"
  fi
  "${CLEAN[@]}" \
    HOME="$site/home" \
    LAUNCHCTL_LOG="$log" \
    SWIFTC_LOG="$site/swiftc.log" \
    PATH="$FAKEBIN:/usr/bin:/bin:/usr/sbin:/sbin" \
    TERMINALONE_APPLICATIONS_DIR="$site/apps" \
    TERMINALONE_BIN_DIR="$site/bin" \
    TERMINALONE_SKIP_LSREGISTER=1 \
    TERMINALONE_SKIP_RUNTIME_CHECK=1 \
    TERMINALONE_SWIFTC="$FAKEBIN/swiftc" \
    bash "$SRC/scripts/$script" > "$site/$script.out" 2>&1
}

show_output() {
  cat "$1/$2.out"
}

# --- 1. Upgrade in place: Townmouse 0.2.x is still installed under TerminalOne's
#        name, in this installation's own directory, and an earlier 0.3.0 stub
#        is already in the bin directory.
new_site upgrade
write_plist "$AGENTS/$LABEL_TERMINALONE.plist" "$SRC/src/server.js"
write_plist "$AGENTS/com.example.other.plist" "$TMP/other/src/server.js"
printf '#!/bin/bash\n# %s\nexit 99\n' "$STUB_MARKER" > "$BIN_DIR/townmouse"
chmod +x "$BIN_DIR/townmouse"
old_launcher_inode="$(stat -f %i "$BIN_DIR/townmouse")"
printf '#!/bin/bash\n# %s\nexit 98\n' "$STUB_MARKER" > "$BIN_DIR/t1"
chmod +x "$BIN_DIR/t1"

run_tool "$SITE" install-service.sh "$SITE/install.log" || { show_output "$SITE" install-service.sh; fail "the installer exited with an error"; }

[ -f "$AGENTS/$LABEL_TOWNMOUSE.plist" ] || fail "the installer did not write Townmouse's plist"
[ ! -e "$AGENTS/$LABEL_TERMINALONE.plist" ] || fail "the 0.2.x service under TerminalOne's label was left in place"
[ -f "$AGENTS/com.example.other.plist" ] || fail "an unrelated launch agent was removed"
grep -q "bootout $DOMAIN/$LABEL_TERMINALONE" "$SITE/install.log" || fail "the 0.2.x service was not stopped"
grep -q "bootstrap $DOMAIN $AGENTS/$LABEL_TOWNMOUSE.plist" "$SITE/install.log" || fail "Townmouse's service was not loaded"
[ ! -e "$BIN_DIR/t1" ] || fail "the t1 launcher that 0.2.x wrote for Townmouse was left behind"
grep -q 'legacy: removed' "$SITE/install-service.sh.out" || fail "the installer did not report what it retired"

PLIST_PATH="$AGENTS/$LABEL_TOWNMOUSE.plist"
grep -q "<string>$LABEL_TOWNMOUSE</string>" "$PLIST_PATH" || fail "the plist carries the wrong label"
grep -q "<string>$SRC/src/server.js</string>" "$PLIST_PATH" || fail "the plist does not run this installation's server"
grep -q '<key>PORT</key><string>11002</string>' "$PLIST_PATH" || fail "the plist does not set Townmouse's port"
grep -q "<string>$HOME_DIR/Library/Logs/$LABEL_TOWNMOUSE.out.log</string>" "$PLIST_PATH" || fail "the plist does not log under Townmouse's name"
if grep -q -E 'com\.floyd\.terminalone|11001' "$PLIST_PATH"; then
  fail "the plist mentions TerminalOne's label or port"
fi

LAUNCHER_PATH="$BIN_DIR/townmouse"
[ -x "$LAUNCHER_PATH" ] || fail "the installer did not write an executable townmouse launcher"
[ "$(stat -f %i "$LAUNCHER_PATH")" != "$old_launcher_inode" ] || fail "an earlier townmouse launcher was not replaced"
grep -q "^$STUB_MARKER" "$LAUNCHER_PATH" || fail "the launcher does not identify itself as Townmouse's"
grep -q "TOWNMOUSE_APP=\"$SRC/scripts/townmouse.sh\"" "$LAUNCHER_PATH" || fail "the launcher does not delegate to this installation"
grep -q 'exec /bin/bash "$TOWNMOUSE_APP" "$@"' "$LAUNCHER_PATH" || fail "the launcher does not pass arguments through"
help_output="$("${CLEAN[@]}" HOME="$HOME_DIR" PATH="$FAKEBIN:/usr/bin:/bin:/usr/sbin:/sbin" "$LAUNCHER_PATH" --help)"
grep -q '^Usage: townmouse ' <<< "$help_output" || fail "the installed launcher does not answer --help"
version_output="$("${CLEAN[@]}" HOME="$HOME_DIR" PATH="$FAKEBIN:/usr/bin:/bin:/usr/sbin:/sbin" "$LAUNCHER_PATH" --version)"
expected="$(sed -n 's/^  "version": "\([^"]*\)".*/\1/p' "$ROOT/package.json" | head -n 1)"
[ "$version_output" = "$expected" ] || fail "the installed launcher printed '$version_output' for --version, expected '$expected'"

APP_EXEC="$APP_PARENT/Townmouse.app/Contents/MacOS/Townmouse"
APP_PLIST="$APP_PARENT/Townmouse.app/Contents/Info.plist"
[ -f "$APP_EXEC" ] || fail "the installer did not build Townmouse.app"
file "$APP_EXEC" | grep -q 'Mach-O.*executable' || fail "the app binary is not a Mach-O executable"
grep -q '<string>com.floyd.townmouse</string>' "$APP_PLIST" || fail "the app bundle carries the wrong identifier"
[ "$(cat "$APP_PARENT/Townmouse.app/Contents/Resources/launcher-path.txt")" = "$LAUNCHER_PATH" ] || fail "the app bundle does not point at the installed launcher"
# Without an explicit target the compiler stamps a macOS of its own choosing,
# and Launch Services refuses an icon that demands a newer system than this Mac.
grep -q -- "-target $(uname -m)-apple-macosx" "$SITE/swiftc.log" || fail "the wrapper is compiled without an explicit macOS target"

if grep -q '/Volumes/ExampleDisk/OriginalInstall' "$PLIST_PATH" "$LAUNCHER_PATH" "$APP_PLIST"; then
  fail "generated artifacts still reference the original machine path"
fi

# --- 2. Beside a real TerminalOne, in either layout: its service and launcher
#        are left alone, and nothing is reported about them.
for layout in "$TMP/elsewhere/TerminalOne" "$TMP/elsewhere/townmouse/terminalone"; do
  new_site beside
  mkdir -p "$layout/src"
  printf '{"name":"terminalone","version":"1.1.0"}\n' > "$layout/package.json"
  write_plist "$AGENTS/$LABEL_TERMINALONE.plist" "$layout/src/server.js"
  printf '#!/bin/bash\necho terminalone\n' > "$BIN_DIR/t1"
  chmod +x "$BIN_DIR/t1"
  foreign_inode="$(stat -f %i "$BIN_DIR/t1")"

  run_tool "$SITE" install-service.sh "$SITE/install.log" || { show_output "$SITE" install-service.sh; fail "the installer exited with an error beside TerminalOne ($layout)"; }

  [ -f "$AGENTS/$LABEL_TERMINALONE.plist" ] || fail "the installer removed TerminalOne's service ($layout)"
  if grep -q "bootout $DOMAIN/$LABEL_TERMINALONE" "$SITE/install.log"; then
    fail "the installer stopped TerminalOne's service ($layout)"
  fi
  if [ ! -f "$BIN_DIR/t1" ] || [ "$(stat -f %i "$BIN_DIR/t1")" != "$foreign_inode" ]; then
    fail "the installer replaced a t1 launcher it did not write ($layout)"
  fi
  if grep -q 'legacy:' "$SITE/install-service.sh.out"; then
    fail "the installer reported a legacy service where only TerminalOne's exists ($layout)"
  fi
  [ -f "$AGENTS/$LABEL_TOWNMOUSE.plist" ] || fail "the installer did not write Townmouse's plist beside TerminalOne ($layout)"
done

# --- 2b. A 0.2.x service in a folder with any name is recognised by the package
#         beside its server and retired.
new_site renamed-install
OLD="$TMP/old-install/a-checkout-with-another-name"
mkdir -p "$OLD/src"
printf '{"name":"townmouse","version":"0.2.1"}\n' > "$OLD/package.json"
write_plist "$AGENTS/$LABEL_TERMINALONE.plist" "$OLD/src/server.js"
run_tool "$SITE" install-service.sh "$SITE/install.log" || { show_output "$SITE" install-service.sh; fail "the installer exited with an error on a renamed 0.2.x install"; }
[ ! -e "$AGENTS/$LABEL_TERMINALONE.plist" ] || fail "a 0.2.x service in a folder with another name was left in place"
grep -q "bootout $DOMAIN/$LABEL_TERMINALONE" "$SITE/install.log" || fail "a 0.2.x service in a folder with another name was not stopped"

# --- 2c. A service under TerminalOne's label that cannot be classified is left
#         alone, and the installer says so.
new_site unknown-service
write_plist "$AGENTS/$LABEL_TERMINALONE.plist" "$TMP/unknown/app/src/server.js"
run_tool "$SITE" install-service.sh "$SITE/install.log" || { show_output "$SITE" install-service.sh; fail "the installer exited with an error beside an unknown service"; }
[ -f "$AGENTS/$LABEL_TERMINALONE.plist" ] || fail "a service that could not be classified was removed"
grep -q 'could not be told from Townmouse' "$SITE/install-service.sh.out" || fail "the installer did not report the service it could not classify"

# --- 3. Uninstall removes Townmouse's service, launcher and app, and nothing else.
new_site uninstall
run_tool "$SITE" install-service.sh "$SITE/install.log" || { show_output "$SITE" install-service.sh; fail "the installer exited with an error in the uninstall scenario"; }
[ -f "$BIN_DIR/townmouse" ] && [ -d "$APP_PARENT/Townmouse.app" ] || fail "the uninstall scenario needs an installed Townmouse"
mkdir -p "$TMP/elsewhere/TerminalOne/src"
printf '{"name":"terminalone","version":"1.1.0"}\n' > "$TMP/elsewhere/TerminalOne/package.json"
write_plist "$AGENTS/$LABEL_TERMINALONE.plist" "$TMP/elsewhere/TerminalOne/src/server.js"
mkdir -p "$APP_PARENT/TerminalOne.app/Contents"
printf 'TerminalOne\n' > "$APP_PARENT/TerminalOne.app/Contents/Info.plist"
printf '#!/bin/bash\necho terminalone\n' > "$BIN_DIR/t1"
printf '#!/bin/bash\necho someone else\n' > "$BIN_DIR/unrelated"
chmod +x "$BIN_DIR/t1" "$BIN_DIR/unrelated"

run_tool "$SITE" uninstall-service.sh "$SITE/uninstall.log" || { show_output "$SITE" uninstall-service.sh; fail "the uninstaller exited with an error"; }

[ ! -e "$AGENTS/$LABEL_TOWNMOUSE.plist" ] || fail "the uninstaller left Townmouse's plist"
grep -q "bootout $DOMAIN/$LABEL_TOWNMOUSE" "$SITE/uninstall.log" || fail "the uninstaller did not stop Townmouse's service"
[ ! -e "$BIN_DIR/townmouse" ] || fail "the uninstaller left the townmouse launcher"
[ ! -d "$APP_PARENT/Townmouse.app" ] || fail "the uninstaller left Townmouse.app"
[ -f "$AGENTS/$LABEL_TERMINALONE.plist" ] || fail "the uninstaller removed TerminalOne's service"
[ -f "$APP_PARENT/TerminalOne.app/Contents/Info.plist" ] || fail "the uninstaller removed TerminalOne.app"
[ -f "$BIN_DIR/t1" ] || fail "the uninstaller removed a t1 launcher it did not write"
[ -f "$BIN_DIR/unrelated" ] || fail "the uninstaller removed an unrelated command"
if grep -q "$LABEL_TERMINALONE" "$SITE/uninstall.log"; then
  fail "the uninstaller touched TerminalOne's service"
fi

# --- 3b. npm's own `townmouse` command is a symlink. The uninstaller never
#         removes a symlink of that name.
new_site npm-command
ln -s "$NPM_TARGET" "$BIN_DIR/townmouse"
run_tool "$SITE" uninstall-service.sh "$SITE/uninstall.log" || { show_output "$SITE" uninstall-service.sh; fail "the uninstaller exited with an error beside npm's command"; }
[ -L "$BIN_DIR/townmouse" ] || fail "the uninstaller removed a symlink named townmouse"
[ "$(readlink "$BIN_DIR/townmouse")" = "$NPM_TARGET" ] || fail "the uninstaller changed npm's townmouse command"

# --- 4. Uninstall on a Mac that never upgraded: the 0.2.x service is retired too.
new_site never-upgraded
write_plist "$AGENTS/$LABEL_TERMINALONE.plist" "$TMP/old/townmouse/src/server.js"
run_tool "$SITE" uninstall-service.sh "$SITE/uninstall.log" || { show_output "$SITE" uninstall-service.sh; fail "the uninstaller exited with an error on a never-upgraded Mac"; }
[ ! -e "$AGENTS/$LABEL_TERMINALONE.plist" ] || fail "the uninstaller left the 0.2.x service under TerminalOne's label"
grep -q "bootout $DOMAIN/$LABEL_TERMINALONE" "$SITE/uninstall.log" || fail "the uninstaller did not stop the 0.2.x service"
grep -q 'legacy: removed' "$SITE/uninstall-service.sh.out" || fail "the uninstaller did not report what it retired"

# --- 5. A `townmouse` the installer did not write (npm's command) is never
#         overwritten, and the install stops before changing anything.
new_site foreign-launcher
ln -s "$NPM_TARGET" "$BIN_DIR/townmouse"
if run_tool "$SITE" install-service.sh "$SITE/install.log"; then
  show_output "$SITE" install-service.sh
  fail "the installer accepted a directory that holds a townmouse command it did not write"
fi
grep -q 'will not be overwritten' "$SITE/install-service.sh.out" || fail "the installer did not explain why it stopped"
[ -L "$BIN_DIR/townmouse" ] && [ "$(readlink "$BIN_DIR/townmouse")" = "$NPM_TARGET" ] || fail "the installer replaced npm's townmouse command"
[ ! -e "$AGENTS/$LABEL_TOWNMOUSE.plist" ] || fail "the installer went on to write its plist after refusing"
if [ -f "$SITE/install.log" ] && grep -q 'bootstrap' "$SITE/install.log"; then
  fail "the installer loaded a service after refusing"
fi
[ ! -d "$APP_PARENT/Townmouse.app" ] || fail "the installer built an app after refusing"

echo "PASS: installer and uninstaller use com.floyd.townmouse on 11002, retire the 0.2.x service, leave npm's command and TerminalOne alone"
