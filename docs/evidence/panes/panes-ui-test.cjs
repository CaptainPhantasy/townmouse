const { spawn } = require('child_process');
const http = require('http');
const fs = require('fs');
const path = require('path');
const puppeteer = require('puppeteer');
const ROOT='/Volumes/SanDisk1Tb/TOWNMOUSE/repo', PORT=11363, BASE=`http://127.0.0.1:${PORT}`;
const OUT='/Volumes/SanDisk1Tb/TOWNMOUSE/stewardship/screens/pass18';
const wait=(ms)=>new Promise(r=>setTimeout(r,ms));
(async()=>{
  fs.mkdirSync(OUT,{recursive:true});
  const fixture=http.createServer((q,s)=>{s.setHeader('Content-Type','text/html');s.end('<title>Pane Fixture</title><h1>Pane Fixture</h1>');}).listen(11364,'127.0.0.1');
  const srv=spawn(process.execPath,[ROOT+'/src/server.js'],{cwd:ROOT,env:{...process.env,PORT:String(PORT),SHELL:'/bin/bash'},stdio:['ignore','ignore','pipe']});
  let err=''; srv.stderr.on('data',d=>err+=d);
  for(let i=0;i<100;i++){try{const r=await fetch(BASE+'/health');if(r.ok)break;}catch(e){}await wait(150);}
  const b=await (await fetch(BASE+'/api/panes/bootstrap')).json();
  const headers={'Content-Type':'application/json','X-Townmouse-Token':b.token};
  const post=(u,d)=>fetch(BASE+'/api/panes'+u,{method:'POST',headers,body:JSON.stringify(d||{})}).then(r=>r.json());
  const tab=await post('/tabs',{title:'Four Panes'});
  const t1=await post(`/tabs/${tab.id}/panes`,{kind:'terminal',title:'Orchestrator'});
  const t2=await post(`/tabs/${tab.id}/panes`,{kind:'terminal',title:'Worker'});
  const br1=await post(`/tabs/${tab.id}/panes`,{kind:'browser',url:'http://127.0.0.1:11364/'});
  const br2=await post(`/tabs/${tab.id}/panes`,{kind:'browser',url:'http://127.0.0.1:11364/'});
  await post(`/panes/${t1.id}/command`,{command:"printf 'ORCHESTRATOR_READY\\n'"});
  await post(`/panes/${t2.id}/command`,{command:"printf 'WORKER_READY\\n'"});
  const brow=await puppeteer.launch({headless:true,args:['--no-sandbox','--disable-setuid-sandbox']});
  const ctx=await brow.createBrowserContext(); const p=await ctx.newPage();
  const errors=[]; p.on('console',m=>{if(m.type()==='error') errors.push(m.text().slice(0,200))});
  await p.setViewport({width:1440,height:900,deviceScaleFactor:1});
  await p.goto(BASE+'/panes.html',{waitUntil:'domcontentloaded'});
  await p.waitForFunction(()=>window.__panes?.state,{timeout:15000});
  await p.waitForFunction(()=>document.querySelectorAll('.pane').length===4,{timeout:15000});
  await p.waitForFunction(()=>document.querySelectorAll('.browser-image').length===2 && [...document.querySelectorAll('.browser-image')].every(i=>i.src.startsWith('data:image')),{timeout:20000});
  await p.waitForFunction(()=>document.querySelectorAll('.xterm').length>=2,{timeout:15000});
  await wait(1200);
  const desktop=await p.evaluate(()=>({count:document.querySelector('#pane-grid').dataset.count,panes:document.querySelectorAll('.pane').length,terms:document.querySelectorAll('.xterm').length,images:document.querySelectorAll('.browser-image').length,titles:[...document.querySelectorAll('.pane-title')].map(e=>e.textContent),tabCount:document.querySelector('#tab-count')?.textContent}));
  await p.screenshot({path:path.join(OUT,'panes-desktop.png')});
  await p.evaluate(()=>document.querySelector('#tabs-button').click()); await wait(300);
  const sheet=await p.evaluate(()=>({open:document.querySelector('#tabs-dialog').open,rows:document.querySelectorAll('#tabs-list .tab-row, #tabs-list li').length}));
  await p.screenshot({path:path.join(OUT,'panes-tabs-dialog.png')});
  await p.evaluate(()=>document.querySelector('#tabs-dialog')?.close());
  console.log('DESKTOP',JSON.stringify({desktop,sheet,errors}));
  await p.setViewport({width:393,height:852,deviceScaleFactor:3,hasTouch:true,isMobile:true}); await wait(800);
  const phone=await p.evaluate(()=>({count:document.querySelector('#pane-grid').dataset.count,panes:document.querySelectorAll('.pane').length,bar:!!document.querySelector('#pane-bar'),tabCount:document.querySelector('#tab-count')?.textContent}));
  await p.screenshot({path:path.join(OUT,'panes-phone.png')});
  console.log('PHONE',JSON.stringify(phone));
  await brow.close(); srv.kill(); fixture.close();
  if(err.trim()) console.log('SERVERERR',err.slice(-300));
})();
